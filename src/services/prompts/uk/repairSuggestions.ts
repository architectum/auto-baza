import { RepairSuggestionsPromptParams } from '../types';

export function repairSuggestionsPrompt({
  problem,
  make,
  model,
  year
}: RepairSuggestionsPromptParams): string {
  const yearText = year ? ` (${year} року випуску)` : '';
  return `Ти — досвідчений сертифікований автомайстер. На основі описаної проблеми з авто ${make} ${model}${yearText}:
"${problem}"

Запропонуй від 3 до 5 можливих конкретних рішень або варіантів усунення цієї несправності. Враховуй типові несправності, сервісні бюлетені та особливості конструкції цієї марки і моделі.

ВАЖЛИВО: Відповідь надай українською мовою як JSON-масив коротких, чітких і зрозумілих рядків (лише тексти рішень). Якщо опис проблеми наведено іншою мовою, сформулюй відповіді українською.`;
}
