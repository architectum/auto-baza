import { DamagePhotoPromptParams } from '../types';

export function damagePhotoPrompt({ make, model }: DamagePhotoPromptParams): string {
  const carInfo = make && model ? ` автомобіля ${make} ${model}` : '';
  return `Проаналізуй це фото пошкодження${carInfo}.
Опиши:
1) description: Детальний тип і точну локалізацію пошкодження (наприклад, подряпина бампера, вм'ятина крила, тріщина фари тощо).
2) severity: Ступінь серйозності пошкодження (строго обери одне значення з: 'minor' (незначне), 'moderate' (середнє), 'severe' (важке/критичне)).
3) estimatedParts: Орієнтовний список деталей, елементів кузова чи вузлів, які можуть потребувати заміни, рихтування або фарбування.

ВАЖЛИВО: Відповідь надішли українською мовою у форматі JSON відповідно до вказаної схеми. Усі описи та назви деталей мають бути українською мовою.`;
}

export const errorDescription = "Не вдалося проаналізувати фото.";
